#!/usr/bin/env python3
"""The panel tab icons, drawn once on a 24x24 grid (stroked, round caps) and written out
for both front ends: android/.../PanelIcons.kt and ios/NarSil/PanelIcons.swift.
Paths use only absolute M L C Z, so neither side needs an SVG parser."""
import re, pathlib

K = 0.5523
def circle(cx, cy, r):
    k = r * K
    return (f"M{cx} {cy-r} C{cx+k} {cy-r} {cx+r} {cy-k} {cx+r} {cy} C{cx+r} {cy+k} {cx+k} {cy+r} {cx} {cy+r} "
            f"C{cx-k} {cy+r} {cx-r} {cy+k} {cx-r} {cy} C{cx-r} {cy-k} {cx-k} {cy-r} {cx} {cy-r} Z")

ICONS = [
    ("pack",      "M7 9 C7 6.5 9 5.5 12 5.5 C15 5.5 17 6.5 17 9 L18 19 C18 20.2 17.5 21 16.5 21 L7.5 21 C6.5 21 6 20.2 6 19 Z "
                  "M10 5.5 C10 3 14 3 14 5.5 M7 12.5 C9 14.5 15 14.5 17 12.5 M10.5 18 L13.5 18"),
    ("character", circle(12, 8, 3.6) + " M5 20.5 C5 16 8 13.8 12 13.8 C16 13.8 19 16 19 20.5"),
    ("skills",    "M12 2.5 L14.2 5 L14.2 15 L9.8 15 L9.8 5 Z M6.5 15 L17.5 15 M12 15 L12 21"),
    ("abilities", "M12 3 C12.5 8.5 15.5 11.5 21 12 C15.5 12.5 12.5 15.5 12 21 C11.5 15.5 8.5 12.5 3 12 C8.5 11.5 11.5 8.5 12 3 Z"),
    ("knowledge", "M12 6 C10 4.5 6.5 4.5 3.5 5.5 L3.5 18.5 C6.5 17.5 10 17.5 12 19 C14 17.5 17.5 17.5 20.5 18.5 "
                  "L20.5 5.5 C17.5 4.5 14 4.5 12 6 Z M12 6 L12 19"),
    ("smithing",  "M3.5 8 L17 8 C17 10.5 15 11.5 13.5 11.5 L13.5 14.5 L17 17 L17 19.5 L6 19.5 L6 17 L9.5 14.5 L9.5 11.5 "
                  "C6 11.5 4.5 10 3.5 8 Z M17 8 L21 8 C21 9.8 19.5 10.8 17.5 10.8"),
    ("options",   "M4 7 L7 7 M11 7 L20 7 " + circle(9, 7, 2) + " M4 12 L13 12 M17 12 L20 12 " + circle(15, 12, 2) +
                  " M4 17 L6 17 M10 17 L20 17 " + circle(8, 17, 2)),
]

def segments(d):
    return [(m.group(1), [float(x) for x in m.group(2).split()])
            for m in re.finditer(r"([MLCZ])([^MLCZ]*)", d)]

root = pathlib.Path(__file__).resolve().parent.parent
kt = ["package org.narsil.android", "",
      "/* Generated by tools/gen-panel-icons.py; do not edit. */", "",
      "/** Panel tab icons as SVG path data on a 24x24 grid (absolute M L C Z), in tab order. */",
      "val PANEL_ICON_PATHS = listOf("]
kt += [f'    "{" ".join(c + " ".join(f"{v:g}" for v in a) for c, a in segments(d))}",  // {n}' for n, d in ICONS]
kt += [")", ""]
(root / "android/app/src/main/kotlin/org/narsil/android/PanelIcons.kt").write_text("\n".join(kt))

sw = ["import SwiftUI", "", "// Generated by tools/gen-panel-icons.py; do not edit.", "",
      "/// Panel tab icons on a 24x24 grid, in tab order; stroke them with round caps.",
      "let panelIconBuilders: [(inout Path) -> Void] = ["]
for n, d in ICONS:
    body = []
    for c, a in segments(d):
        p = [f"CGPoint(x: {a[i]:g}, y: {a[i+1]:g})" for i in range(0, len(a), 2)]
        body.append({"M": f"$0.move(to: {p[0] if p else ''})", "L": f"$0.addLine(to: {p[0] if p else ''})",
                     "C": f"$0.addCurve(to: {p[2] if len(p)>2 else ''}, control1: {p[0] if p else ''}, control2: {p[1] if len(p)>1 else ''})",
                     "Z": "$0.closeSubpath()"}[c])
    sw.append(f"    {{ // {n}")
    sw += [f"        {b}" for b in body]
    sw.append("    },")
sw += ["]", "",
       "struct PanelIcon: Shape {",
       "    let index: Int",
       "    func path(in rect: CGRect) -> Path {",
       "        var p = Path()",
       "        panelIconBuilders[index](&p)",
       "        let s = min(rect.width, rect.height) / 24",
       "        return p.applying(CGAffineTransform(scaleX: s, y: s))",
       "    }",
       "}", ""]
(root / "ios/NarSil/PanelIcons.swift").write_text("\n".join(sw))
