#!/usr/bin/env python3
"""Shared UI text for both apps: the Help touch guide (ui/touch-guide.txt) and the first-run tips
(ui/first-run.txt) become
android/.../TouchGuide.kt and ios/NarSil/TouchGuide.swift, so the apps cannot drift apart."""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
check = "--check" in sys.argv  # exit 1 if a generated file is out of date, instead of writing it
stale = []

def write(path, text):
    if not check:
        path.write_text(text)
    elif not path.exists() or path.read_text() != text:
        stale.append(str(path.relative_to(root)))

def guide(platform, name="touch-guide.txt"):
    sections = []
    for line in (root / "ui" / name).read_text().splitlines():
        if line.startswith("## "):
            sections.append((line[3:].strip(), []))
        elif line.startswith("- "):
            m = re.match(r"- (?:\[(\w+)\] )?(.*)", line)
            assert sections, "a point before the first section"
            if m.group(1) in (None, platform):
                sections[-1][1].append(m.group(2))
            else:
                assert m.group(1) in ("android", "ios"), line
    return sections

def kt(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'
def sw(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = ["package org.narsil.android", "", "/* Generated by tools/gen-shared-ui.py from ui/touch-guide.txt; do not edit. */", "",
       "/** Help's touch-controls guide: headings and their points. */",
       "internal val TOUCH_GUIDE: List<Pair<String, List<String>>> = listOf("]
for title, points in guide("android"):
    out.append(f"    {kt(title)} to listOf(")
    out += [f"        {kt(p)}," for p in points]
    out.append("    ),")
out += [")", ""]
[(tips_title, tips)] = guide("android", "first-run.txt")
out += ["/** The tips card shown once, the first time the map appears (ui/first-run.txt). */",
        f"internal const val FIRST_RUN_TITLE = {kt(tips_title)}",
        "internal val FIRST_RUN_TIPS: List<String> = listOf("] + [f"    {kt(p)}," for p in tips] + [")", ""]
write(root / "android/app/src/main/kotlin/org/narsil/android/TouchGuide.kt", "\n".join(out))

out = ["// Generated by tools/gen-shared-ui.py from ui/touch-guide.txt; do not edit.", "",
       "/// Help's touch-controls guide: headings and their points.",
       "let touchGuide: [(String, [String])] = ["]
for title, points in guide("ios"):
    out.append(f"    ({sw(title)}, [")
    out += [f"        {sw(p)}," for p in points]
    out.append("    ]),")
out += ["]", ""]
[(tips_title, tips)] = guide("ios", "first-run.txt")
out += ["/// The tips card shown once, the first time the map appears (ui/first-run.txt).",
        f"let firstRunTitle = {sw(tips_title)}",
        "let firstRunTips: [String] = ["] + [f"    {sw(p)}," for p in tips] + ["]", ""]
write(root / "ios/NarSil/TouchGuide.swift", "\n".join(out))

if stale:
    print(f"out of date (run {pathlib.Path(__file__).relative_to(root)}): " + ", ".join(stale))
    sys.exit(1)
